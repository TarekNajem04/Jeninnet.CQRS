[CmdletBinding()]
param(
    [switch]$Check,
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path $Root).Path
Push-Location $repoRoot
try {
    $files = @(git ls-files '*.cs' '*.ps1' | Sort-Object)

    $headerLines = @(
        'Copyright (c) Jeninnet.',
        'Part of the Jeninnet Platform.',
        'Solution Repository: https://github.com/TarekNajem04/Jeninnet.CQRS',
        'Licensed under the MIT License.'
    )

    $missing = [System.Collections.Generic.List[string]]::new()
    $updated = 0

    foreach ($relativePath in $files) {
        $path = Join-Path $repoRoot $relativePath
        if (-not (Test-Path -LiteralPath $path)) { continue }

        $extension = [IO.Path]::GetExtension($path).ToLowerInvariant()
        if ($extension -notin '.cs', '.ps1') { continue }

        if ($relativePath -match '(^|/)(bin|obj|Generated|Migrations)/') { continue }
        if ($relativePath -match '\.(g|Designer|generated)\.cs$' -or $relativePath -match 'AssemblyInfo\.cs$') { continue }

        $bytes = [IO.File]::ReadAllBytes($path)
        $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
        $text = [IO.File]::ReadAllText($path)

        $firstLines = @($text -split "`r?`n" | Select-Object -First 10)
        if ($firstLines -match '<auto-generated|GeneratedCodeAttribute') { continue }
        if ($firstLines -match 'Copyright \(c\) Jeninnet\.') { continue }

        if ($Check) {
            $missing.Add($relativePath)
            continue
        }

        $newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
        $comment = if ($extension -eq '.ps1') { '#' } else { '//' }
        $header = (@(
            $comment
            "$comment Copyright (c) Jeninnet."
            "$comment Part of the Jeninnet Platform."
            "$comment Solution Repository: https://github.com/TarekNajem04/Jeninnet.CQRS"
            "$comment Licensed under the MIT License."
            $comment
        ) -join $newline) + $newline

        [IO.File]::WriteAllText($path, $header + $text, [Text.UTF8Encoding]::new($hasBom))
        $updated++
    }

    if ($Check) {
        if ($missing.Count -gt 0) {
            Write-Host "Missing header in $($missing.Count) file(s):" -ForegroundColor Yellow
            $missing | ForEach-Object { Write-Host "  $_" }
            exit 1
        }
        Write-Host "All tracked .cs and .ps1 files have the approved header."
        exit 0
    }

    Write-Host "Added the header to $updated file(s)."
}
finally {
    Pop-Location
}
