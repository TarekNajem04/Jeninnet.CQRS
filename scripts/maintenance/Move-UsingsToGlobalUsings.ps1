[CmdletBinding()]
param(
    [switch]$Check,
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path $Root).Path
Push-Location $repoRoot
try {
    $projectFiles = @(Get-ChildItem $repoRoot -Recurse -Filter *.csproj -File |
        Where-Object { $_.FullName -notmatch '\\(bin|obj|artifacts)\\' } |
        Sort-Object { $_.DirectoryName.Length } -Descending)

    if ($projectFiles.Count -eq 0) { throw "No .csproj files found." }

    function Get-ProjectForFile {
        param([string]$FullPath)
        foreach ($project in $projectFiles) {
            $prefix = $project.DirectoryName.TrimEnd('\') + '\'
            if ($FullPath.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase)) {
                return $project
            }
        }
        return $null
    }

    $usingPattern = '^\s*using\s+(?<body>[A-Za-z_][A-Za-z0-9_.]*(?:\s*=\s*[A-Za-z_][A-Za-z0-9_.]*)?)\s*;\s*(?://.*)?$'
    $files = @(git ls-files '*.cs' | Sort-Object)
    $projectUsings = @{}
    $changedFiles = [System.Collections.Generic.List[string]]::new()
    $keptLocal = [System.Collections.Generic.List[string]]::new()

    foreach ($relativePath in $files) {
        if ($relativePath -match 'GlobalUsings\.cs$') { continue }
        if ($relativePath -match '(^|/)(bin|obj|Generated|Migrations)/') { continue }
        if ($relativePath -match '\.(g|Designer|generated)\.cs$' -or $relativePath -match 'AssemblyInfo\.cs$') { continue }
        if ($relativePath -like 'src/Jeninnet.CQRS.Polyfills/*') { continue }

        $path = Join-Path $repoRoot $relativePath
        if (-not (Test-Path -LiteralPath $path)) { continue }

        $project = Get-ProjectForFile $path
        if ($null -eq $project) { continue }

        $bytes = [IO.File]::ReadAllBytes($path)
        $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
        $text = [IO.File]::ReadAllText($path)
        $firstLines = @($text -split "`r?`n" | Select-Object -First 5)
        if ($firstLines -match '<auto-generated|GeneratedCodeAttribute') { continue }

        $newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
        $lines = [System.Collections.Generic.List[string]]::new([string[]]($text -split "`r?`n"))

        $namespaceIndex = -1
        for ($i = 0; $i -lt $lines.Count; $i++) {
            if ($lines[$i] -match '^\s*namespace\s+') { $namespaceIndex = $i; break }
        }

        $limit = if ($namespaceIndex -ge 0) { $namespaceIndex } else { $lines.Count }
        $ifDepth = 0
        $remove = [System.Collections.Generic.List[int]]::new()

        for ($i = 0; $i -lt $limit; $i++) {
            $line = $lines[$i]
            if ($line -match '^\s*#if\b') { $ifDepth++; continue }
            if ($line -match '^\s*#endif\b') { if ($ifDepth -gt 0) { $ifDepth-- }; continue }
            if ($ifDepth -gt 0) { continue }

            if ($line -notmatch $usingPattern) { continue }
            $body = $Matches['body']
            if ($body -match '^\s*static\s' -or $body -match '=') {
                $keptLocal.Add("$relativePath : $body")
                continue
            }

            $key = $project.FullName
            if (-not $projectUsings.ContainsKey($key)) {
                $projectUsings[$key] = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
            }
            [void]$projectUsings[$key].Add($body)
            $remove.Add($i)
        }

        if ($remove.Count -eq 0) { continue }
        $changedFiles.Add($relativePath)

        if ($Check) { continue }

        for ($i = $remove.Count - 1; $i -ge 0; $i--) {
            $lines.RemoveAt($remove[$i])
        }

        [IO.File]::WriteAllText($path, ($lines -join $newline), [Text.UTF8Encoding]::new($hasBom))
    }

    if ($Check) {
        if ($changedFiles.Count -gt 0) {
            Write-Host "Files with movable top-level usings: $($changedFiles.Count)" -ForegroundColor Yellow
            $changedFiles | Select-Object -First 60 | ForEach-Object { Write-Host "  $_" }
            if ($keptLocal.Count -gt 0) {
                Write-Host "Kept local (alias/static): $($keptLocal.Count)"
            }
            exit 1
        }
        Write-Host "No movable top-level usings remain."
        exit 0
    }

    $updatedGlobalFiles = 0
    foreach ($projectPath in $projectUsings.Keys) {
        $projectDir = Split-Path $projectPath -Parent
        $globalPath = Join-Path $projectDir 'GlobalUsings.cs'
        $newUsings = @($projectUsings[$projectPath] | Sort-Object)

        $headerLines = @(
            '//'
            '// Copyright (c) Jeninnet.'
            '// Part of the Jeninnet Platform.'
            '// Solution Repository: https://github.com/TarekNajem04/Jeninnet.CQRS'
            '// Licensed under the MIT License.'
            '//'
        )
        $existingGlobals = @()
        $newline = "`r`n"
        $hasBom = $true

        if (Test-Path -LiteralPath $globalPath) {
            $bytes = [IO.File]::ReadAllBytes($globalPath)
            $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
            $text = [IO.File]::ReadAllText($globalPath)
            $newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
            $existingGlobals = @($text -split "`r?`n" | Where-Object { $_ -match '^\s*global\s+using\s+' })
        }

        $allGlobals = @($existingGlobals + ($newUsings | ForEach-Object { "global using $_;" })) |
            Sort-Object -Unique
        $content = ($headerLines -join $newline) + $newline + ($allGlobals -join $newline) + $newline
        [IO.File]::WriteAllText($globalPath, $content, [Text.UTF8Encoding]::new($hasBom))
        $updatedGlobalFiles++
    }

    Write-Host "Removed file-level usings from $($changedFiles.Count) file(s)."
    Write-Host "Updated $updatedGlobalFiles GlobalUsings.cs file(s)."
    if ($keptLocal.Count -gt 0) {
        Write-Host "Kept local (alias/static): $($keptLocal.Count)"
        $keptLocal | Select-Object -First 20 | ForEach-Object { Write-Host "  $_" }
    }
}
finally {
    Pop-Location
}
