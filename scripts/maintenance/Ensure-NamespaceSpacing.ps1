[CmdletBinding()]
param(
    [switch]$Check,
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path $Root).Path
Push-Location $repoRoot
try {
    $files = @(git ls-files '*.cs' | Sort-Object)
    $namespacePattern = '^\s*namespace\s+[A-Za-z_][A-Za-z0-9_.]*\s*;(?:\s*//.*)?\s*$'
    $missing = [System.Collections.Generic.List[string]]::new()
    $updated = 0

    foreach ($relativePath in $files) {
        $path = Join-Path $repoRoot $relativePath
        if (-not (Test-Path -LiteralPath $path)) { continue }
        if ($relativePath -match '(^|/)(bin|obj|Generated|Migrations)/') { continue }
        if ($relativePath -match '\.(g|Designer|generated)\.cs$' -or $relativePath -match 'AssemblyInfo\.cs$') { continue }

        $bytes = [IO.File]::ReadAllBytes($path)
        $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
        $text = [IO.File]::ReadAllText($path)
        $firstLines = @($text -split "`r?`n" | Select-Object -First 5)
        if ($firstLines -match '<auto-generated|GeneratedCodeAttribute') { continue }

        $newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
        $lines = [System.Collections.Generic.List[string]]::new([string[]]($text -split "`r?`n"))
        $changed = $false

        for ($i = 0; $i -lt $lines.Count; $i++) {
            if ($lines[$i] -notmatch $namespacePattern) { continue }
            if ($i + 1 -ge $lines.Count) { continue }

            if ($lines[$i + 1].Trim().Length -ne 0) {
                $lines.Insert($i + 1, '')
                $i++
                $changed = $true
            }
        }

        if (-not $changed) { continue }

        if ($Check) {
            $missing.Add($relativePath)
            continue
        }

        [IO.File]::WriteAllText($path, ($lines -join $newline), [Text.UTF8Encoding]::new($hasBom))
        $updated++
    }

    if ($Check) {
        if ($missing.Count -gt 0) {
            Write-Host "Missing blank line after a file-scoped namespace in $($missing.Count) file(s):" -ForegroundColor Yellow
            $missing | ForEach-Object { Write-Host "  $_" }
            exit 1
        }
        Write-Host "All file-scoped namespaces are followed by exactly one blank line."
        exit 0
    }

    Write-Host "Inserted a blank line after the namespace in $updated file(s)."
}
finally {
    Pop-Location
}
